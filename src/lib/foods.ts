export function searchFoods(query: string): Food[] {
  const q = normalizeSearch(query);
  if (!q) return FOODS;
  return FOODS.filter((food) => {
    const hay = normalizeSearch(
      [food.name, food.id, ...food.aliases].join(" "),
    );
    return hay.includes(q);
  });
}
